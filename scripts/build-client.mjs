import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Dependency-free bundler for the DSH browser adapter.
 *
 * DSH loads exactly one client entry through window.__ModuleLoader__, and local
 * ESM imports are not available inside that factory. The readable sources live
 * in lib/client/; this script wraps them in a tiny CommonJS registry and emits
 * the single lib/client.js bundle the Host expects.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const clientDirectory = join(root, "lib", "client");
const output = join(root, "lib", "client.js");
const checkOnly = process.argv.includes("--check");
const moduleFiles = ["constants", "store", "bridge", "theme", "fortune", "merit", "index"];

const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const modules = [];
for (const name of moduleFiles) {
	const source = await readFile(join(clientDirectory, `${name}.js`), "utf8");
	modules.push([`./${name}`, source.trimEnd()]);
}
const fortuneCss = await readFile(join(clientDirectory, "styles", "fortune.css"), "utf8");
const themeCss = await readFile(join(clientDirectory, "styles", "theme-status.css"), "utf8");
modules.push(["./styles", `module.exports = {\n\tFORTUNE_CSS: ${JSON.stringify(fortuneCss)},\n\tTHEME_STATUS_CSS: ${JSON.stringify(themeCss)}\n};`]);

const registry = modules
	.map(([id, source]) => `\t\t${JSON.stringify(id)}: function (module, exports, require) {\n${source.split("\n").map((line) => line.trim() ? `\t\t\t${line}` : "").join("\n")}\n\t\t}`)
	.join(",\n");

const bundle = `/** Generated by scripts/build-client.mjs from lib/client/**. Do not edit directly. */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkg.name)},
\tfactory: (hostRequire) => {
\t\tconst modules = {
${registry}
\t\t};
\t\tconst cache = {};
\t\tfunction localRequire(id) {
\t\t\tconst factory = modules[id];
\t\t\tif (!factory) throw new Error(\`Unknown client module: \${id}\`);
\t\t\tif (!cache[id]) {
\t\t\t\tconst module = { exports: {} };
\t\t\t\tcache[id] = module;
\t\t\t\tfactory(module, module.exports, localRequire);
\t\t\t}
\t\t\treturn cache[id].exports;
\t\t}
\t\treturn localRequire("./index")(hostRequire("react"));
\t}
});
`;

if (checkOnly) {
	const current = await readFile(output, "utf8").catch(() => "");
	if (current !== bundle) {
		console.error("lib/client.js is out of date. Run npm run build:client.");
		process.exit(1);
	}
	console.log("Client bundle is up to date.");
} else {
	await writeFile(output, bundle);
	console.log(`Built ${output} from ${modules.length} client modules.`);
}
